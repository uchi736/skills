class CatalogDeck(Deck):
    """見本専用: 各枚の出典の上に「用途 / 避ける → 代替」の 1 行を置く(本文の下端はその分だけ上がる)。"""

    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self._usage = None

    def usage(self, text):
        self._usage = text

    def _body_bot(self, source=None, note=None):
        b = super()._body_bot(source, note)
        return min(b, self.H - 1.27 - (0.21 if note else 0.0)) if self._usage else b

    def _reserve_takeaway(self, takeaway, source=None, note=None):
        orig = super()._reserve_takeaway(takeaway, source, note)
        if orig is not None and self._usage:
            self.BODY_BOT -= 0.22
        return orig

    def _source(self, s, source, note=None):
        if self._usage:
            u, self._usage = self._usage, None
            self.text(s, self.MX, self.H - 1.13 - (0.21 if note else 0.0), self.CW, 0.22,
                      [[("用途: ", 12, True, BLUE_TX), (u, 12, False, INK2)]])
        super()._source(s, source, note)

